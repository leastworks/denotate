// The editor and checked-program loader share this grammar. Existing node/field
// names are retained for B's current editor projection.
module.exports = grammar({
  name: 'denotate',
  extras: $ => [/[ \t\r\n]+/, $.comment],
  word: $ => $.identifier,
  reserved: { global: $ => ['module', 'namespace', 'use', 'sort', 'const', 'relation', 'input', 'domain', 'obligation', 'assumption', 'verification', 'source'], parameter_names: _ => [] },
  rules: {
    // A file-scoped header may follow only imports (and whitespace/comments).
    // Once a global declaration or namespace block starts, no header can follow.
    source_file: $ => seq(optional('\uFEFF'), repeat($.import), optional(choice(
      seq(choice($.module, alias($._namespace_file, $.namespace)), repeat($._declaration)),
      seq(choice(alias($._namespace_block, $.namespace), $._non_import_declaration), repeat(choice(alias($._namespace_block, $.namespace), $._declaration)))
    ))),
    module: $ => seq('module', field('name', $._namespace_path), ';'),
    _namespace_file: $ => seq('namespace', field('name', $._namespace_path), ';'),
    _namespace_block: $ => seq('namespace', field('name', $._namespace_path), '{', repeat(choice(alias($._namespace_block, $.namespace), $._declaration)), '}'),
    _namespace_path: $ => choice($._name, $.qualified_name),
    _declaration: $ => choice($.import, $._non_import_declaration),
    _non_import_declaration: $ => choice($.sort, $.constants, $.relation, $.statement, $.domain, $.obligation, $.assumption, $.verification, $.source_location, $.location_alias),
    import: $ => seq('use', field('name', $._namespace_path), ';'),
    sort: $ => seq('sort', field('name', $._name), optional($.location), ';'),
    constants: $ => seq('const', field('name', $._constant), repeat(seq(',', field('name', $._constant))), ':', field('sort', $._reference), optional($.location), ';'),
    relation: $ => seq(field('kind', choice('relation', 'input')), field('name', choice($._name, $.generated_identifier)), '(', optional(seq($.parameter, repeat(seq(',', $.parameter)))), ')', optional($.location), ';'),
    parameter: $ => seq(field('name', $._parameter_name), ':', field('sort', $._reference)),
    statement: $ => seq(field('head', $.atom), optional(seq(':-', $._literal, repeat(seq(',', $._literal)))), optional($.location), ';'),
    _literal: $ => choice($.positive_atom, $.negative_atom),
    negative_atom: $ => seq('!', $.atom),
    atom: $ => seq(field('name', $._reference), '(', optional(seq($._named_term, repeat(seq(',', $._named_term)))), ')'),
    positive_atom: $ => seq(field('name', $._reference), '(', optional(seq($._term, repeat(seq(',', $._term)))), ')'),
    _term: $ => choice($._named_term, $.anonymous),
    _named_term: $ => choice($.variable, $._constant_reference),
    _constant_reference: $ => choice($._constant, $.qualified_name),
    _constant: $ => choice($.constant, $.integer, $.quoted_identifier),
    _name: $ => choice($.identifier, $.quoted_identifier),
    _parameter_name: $ => choice(reserved('parameter_names', $.identifier), $.quoted_identifier),
    _reference: $ => choice($._name, $.generated_identifier, $.qualified_name),
    qualified_name: _ => token(/(?:::)?(([A-Za-z][A-Za-z0-9_]*|'([^'\\\r\n]|\\[^\r\n])*')::)+(\$[A-Za-z][A-Za-z0-9_]*|[A-Za-z][A-Za-z0-9_]*|-?[0-9]+|'([^'\\\r\n]|\\[^\r\n])*')|::(\$[A-Za-z][A-Za-z0-9_]*|[A-Za-z][A-Za-z0-9_]*|-?[0-9]+|'([^'\\\r\n]|\\[^\r\n])*')/),
    domain: $ => seq('domain', field('sort', $._reference), '=', '[', optional(seq(field('value', $._constant_reference), repeat(seq(',', field('value', $._constant_reference))))), ']', ';'),
    obligation: $ => seq('obligation', field('name', $._name), ':', $.cardinality, optional(seq('message', field('message', $.string))), optional($.location), ';'),
    assumption: $ => seq('assumption', field('name', $._name), ':', $.cardinality, optional($.location), ';'),
    verification: $ => seq('verification', field('name', $._name), '{', 'assumptions', ':', '[', optional(seq(field('assumption', $._reference), repeat(seq(',', field('assumption', $._reference))))), ']', ';', 'obligations', ':', '[', optional(seq(field('obligation', $._reference), repeat(seq(',', field('obligation', $._reference))))), ']', ';', '}', optional($.location)),
    cardinality: $ => choice(seq(field('kind', 'empty'), '(', field('relation', $._reference), ')'), seq(field('kind', choice('at_most_one', 'at_least_one', 'exactly_one')), '(', field('relation', $._reference), ',', 'group_by', ':', choice(field('column', $._parameter_name), seq('(', optional(seq(field('column', $._parameter_name), repeat(seq(',', field('column', $._parameter_name))))), ')')), ')')),
    location: $ => seq('loc', '(', choice($.location_value, $.compact_map), ')'),
    location_value: $ => choice($.alias, $.source_range, seq('fused', '[', $.location_value, repeat(seq(',', $.location_value)), ']')),
    source_range: $ => seq(field('source', $.alias), $.coordinate_range),
    coordinate_range: $ => seq(field('start', $.coordinate), 'to', field('end', $.coordinate)),
    coordinate: $ => seq(field('line', $.natural), ':', field('column', $.natural)),
    compact_map: $ => seq(field('source', $.alias), '{', optional(seq($.compact_entry, repeat(seq(',', $.compact_entry)))), '}'),
    compact_entry: $ => seq(field('position', $.occurrence_position), ':', $.coordinate_range),
    source_location: $ => seq(field('name', $.alias), '=', 'source', '(', field('uri', $.string), ',', 'view', ':', field('view', $.string), ',', 'hash', ':', field('hash', $.string), ')', ';'),
    location_alias: $ => seq(field('name', $.alias), '=', choice($.location, $.occurrence_map), ';'),
    occurrence_map: $ => seq('{', optional(seq($.location_entry, repeat(seq(',', $.location_entry)))), '}'),
    location_entry: $ => seq(field('position', $.occurrence_position), ':', $.location),
    occurrence_position: _ => token(/(self|head|body\.[0-9]+|decl\.[0-9]+)(\.[0-9]+)?/),
    alias: _ => token(/#[A-Za-z][A-Za-z0-9_]*/),
    natural: _ => /[0-9]+/,
    integer: _ => /-?[0-9]+/,
    anonymous: _ => '_',
    identifier: _ => /[A-Za-z][A-Za-z0-9_]*/,
    generated_identifier: _ => /\$[A-Za-z][A-Za-z0-9_]*/,
    quoted_identifier: _ => token(/'([^'\\\r\n]|\\[^\r\n])*'/),
    string: _ => token(/"([^"\\\r\n]|\\[^\r\n])*"/),
    constant: _ => /[a-z][A-Za-z0-9_]*/,
    variable: $ => choice(/[A-Z][A-Za-z0-9_]*/, seq('?', $.quoted_identifier)),
    comment: _ => token(seq('//', /[^\r\n]*/))
  }
});
